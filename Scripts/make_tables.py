F = C.families()
def fam_mean(fn, n):
    Zs = [Z for fam, m, g, Z in F if fam == "B" and m == n]
    return sum(fn(Z) for Z in Zs) / len(Zs)
def mag_factor(fn):
    a = sum(fn(C.assertion(12, 1, seed=1000 * 12 + s)) for s in range(25)) / 25
    b = sum(fn(C.assertion(12, 16, seed=1000 * 12 + s)) for s in range(25)) / 25
    return b / a
