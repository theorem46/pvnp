def write(name, body):
    with open(os.path.join(OUT, name + ".tex"), "w") as f:
        f.write("% generated by make_tables.py -- do not edit\n" + body)


def fmt(x):
    return f"{x:,.0f}" if abs(x - round(x)) < 1e-9 else f"{x:,.1f}"


