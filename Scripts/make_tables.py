    ("exhaustive survey", lambda Z: C.survey_ops(len(Z)), lambda Z: 2 ** len(Z) - 1),
    ("Bellman table", C.bellman_ops, lambda Z: (sum(v for v in Z if v > 0) - sum(v for v in Z if v < 0) + 1) * len(Z)),
    ("meet-in-the-middle", C.mitm_ops, lambda Z: 2 ** (len(Z) // 2) + 2 ** (len(Z) - len(Z) // 2)),
